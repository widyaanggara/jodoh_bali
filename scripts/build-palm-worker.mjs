import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(projectRoot, "public", "workers", "palm-line.worker.js");
const modules = [
  {
    id: "@/lib/netra-hasta/palm-line-runtime",
    source: "lib/netra-hasta/palm-line-runtime.ts",
  },
  {
    id: "@/lib/netra-hasta/palm-line-live",
    source: "lib/netra-hasta/palm-line-live.ts",
  },
  {
    id: "@/workers/palm-line.worker",
    source: "workers/palm-line.worker.ts",
  },
];

function transpile(sourcePath) {
  const absolutePath = path.join(projectRoot, sourcePath);
  const source = fs.readFileSync(absolutePath, "utf8");
  return ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
      esModuleInterop: true,
      removeComments: true,
    },
    fileName: absolutePath,
  }).outputText.trim();
}

const moduleFactories = modules.map(({ id, source }) =>
  `${JSON.stringify(id)}: function (require, module, exports) {\n${transpile(source)}\n}`
).join(",\n");

const output = `/* AUTO-GENERATED by scripts/build-palm-worker.mjs. Do not edit. */
(function () {
  "use strict";
  const factories = {
${moduleFactories}
  };
  const cache = Object.create(null);
  function require(id) {
    if (id === "./palm-line-runtime") {
      id = "@/lib/netra-hasta/palm-line-runtime";
    }
    if (cache[id]) return cache[id].exports;
    const factory = factories[id];
    if (!factory) throw new Error("Unknown palm worker module: " + id);
    const module = { exports: {} };
    cache[id] = module;
    factory(require, module, module.exports);
    return module.exports;
  }
  require("@/workers/palm-line.worker");
})();
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : null;
if (current !== output) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Generated ${path.relative(projectRoot, outputPath)}`);
} else {
  console.log(`Unchanged ${path.relative(projectRoot, outputPath)}`);
}
